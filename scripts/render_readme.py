#!/usr/bin/env python3
"""Render the spacing section of the README from research/results/spacing_summary.csv.

    python3 scripts/render_readme.py          rewrite the block
    python3 scripts/render_readme.py --check  exit 1 if the README is out of date

The CSV is written by research/analyze_spacing.py from five runs of bench_t2t --gap-sweep.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = "<!-- spacing:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- spacing:end -->"


def gap_label(us: float) -> str:
    if us == 0:
        return "none (back to back)"
    return f"{us / 1000:g} ms" if us >= 1000 else f"{us:g} us"


def render() -> str:
    with (ROOT / "research" / "results" / "spacing_summary.csv").open() as f:
        rows = [{k: float(v) for k, v in r.items()} for r in csv.DictReader(f)]
    by_gap = {r["gap_us"]: r for r in rows}
    base, ms = by_gap[0.0], by_gap[1000.0]
    out = [
        "| Gap before each tick | Ticks timed | Quiet tick p50 | vs back to back | Same, warmed | Order tick p50 |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        warm = f"{r['idle_warm_p50']:.0f} ns" if r["idle_warm_p50"] > 0 else "n/a"
        ratio = "1.0x" if r["gap_us"] == 0 else f"{r['idle_ratio']:.1f}x"
        out.append(
            f"| {gap_label(r['gap_us'])} | {int(r['n_inputs'])} | {r['idle_p50']:.0f} ns | {ratio} | "
            f"{warm} | {r['act_p50']:.0f} ns |"
        )
    out += [
        "",
        f"With a 1 ms gap the median quiet tick costs {ms['idle_p50']:.0f} ns, not {base['idle_p50']:.0f} ns "
        f"({ms['idle_ratio']:.1f} times its matched no-gap control; {ms['idle_ratio_min']:.1f} to "
        f"{ms['idle_ratio_max']:.1f} across the five runs), and a tick that sends an order costs "
        f"{ms['act_p50'] / 1000:.1f} us, not {base['act_p50']:.0f} ns. Running the same code path on a shadow "
        f"instance during the gap (the warmed column) brings the quiet tick back to {ms['idle_warm_p50']:.0f} ns, "
        f"which recovers part of the penalty and not all of it. Order ticks are a small share of each run "
        f"({int(ms['n_act'])} at 1 ms and {int(by_gap[10000.0]['n_act'])} at 10 ms), so the last column is rough "
        f"at the long gaps.",
    ]
    return "\n".join(out)


def main() -> None:
    readme = ROOT / "README.md"
    text = readme.read_text()
    a, b = text.index(START) + len(START), text.index(END)
    new = text[:a] + "\n" + render() + "\n" + text[b:]
    if "--check" in sys.argv:
        if new != text:
            print("README spacing section is out of date; run python3 scripts/render_readme.py")
            sys.exit(1)
        print("README spacing section matches research/results/spacing_summary.csv")
        return
    readme.write_text(new)
    print("README spacing section rendered")


if __name__ == "__main__":
    main()
